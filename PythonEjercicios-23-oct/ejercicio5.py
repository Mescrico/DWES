cadena = "Desarrollo Web en Entorno servidor"

# caracteres
print(len(cadena))

# mayusculas
print(cadena.upper())

# in
print("web" in cadena)

# in con .lower()
print("web" in cadena.lower())

# La diferencia entre no usar y usar .lower() es que al usar .lower() todo el contenido del string pasa a estar en minuscula